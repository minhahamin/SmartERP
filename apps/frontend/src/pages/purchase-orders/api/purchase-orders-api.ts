import { apiClient, type ApiSuccess } from '@/lib/api/client';

export type PurchaseOrderStatus = 'DRAFT' | 'CONFIRMED' | 'RECEIVED' | 'CANCELLED';

export interface PurchaseOrderItem {
  id: string;
  productId: string;
  quantity: number;
  unitCost: string;
  reason: string | null;
  product: { name: string; sku: string; unit: string };
}

export interface PurchaseOrder {
  id: string;
  orderNo: string;
  partnerId: string | null;
  status: PurchaseOrderStatus;
  isAutoGenerated: boolean;
  memo: string | null;
  createdAt: string;
  partner: { id: string; name: string } | null;
  items: PurchaseOrderItem[];
}

export interface GenerateDraftsResult {
  created?: number;
  skipped?: boolean;
  reason?: string;
}

export async function listPurchaseOrders(status?: PurchaseOrderStatus): Promise<PurchaseOrder[]> {
  const { data } = await apiClient.get<ApiSuccess<PurchaseOrder[]>>('/purchase-orders', {
    params: { status, page: 1, limit: 100 },
  });
  return data.data;
}

export async function generatePurchaseDrafts(): Promise<GenerateDraftsResult> {
  const { data } = await apiClient.post<ApiSuccess<GenerateDraftsResult>>('/purchase-orders/generate-drafts');
  return data.data;
}

export interface UpdatePurchaseOrderInput {
  partnerId?: string;
  items?: { itemId: string; quantity: number }[];
}

export async function updatePurchaseOrder(id: string, input: UpdatePurchaseOrderInput): Promise<PurchaseOrder> {
  const { data } = await apiClient.patch<ApiSuccess<PurchaseOrder>>(`/purchase-orders/${id}`, input);
  return data.data;
}

export async function confirmPurchaseOrder(id: string): Promise<PurchaseOrder> {
  const { data } = await apiClient.post<ApiSuccess<PurchaseOrder>>(`/purchase-orders/${id}/confirm`);
  return data.data;
}

export async function cancelPurchaseOrder(id: string): Promise<PurchaseOrder> {
  const { data } = await apiClient.post<ApiSuccess<PurchaseOrder>>(`/purchase-orders/${id}/cancel`);
  return data.data;
}

export async function receivePurchaseOrder(id: string, warehouseId: string): Promise<PurchaseOrder> {
  const { data } = await apiClient.post<ApiSuccess<PurchaseOrder>>(`/purchase-orders/${id}/receive`, { warehouseId });
  return data.data;
}
