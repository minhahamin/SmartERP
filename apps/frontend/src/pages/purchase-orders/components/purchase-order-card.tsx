import { useState } from 'react';
import { Badge } from '@/components/ui/badge';
import { Button } from '@/components/ui/button';
import { Card } from '@/components/ui/card';
import { Input } from '@/components/ui/input';
import { Select, SelectContent, SelectItem, SelectTrigger, SelectValue } from '@/components/ui/select';
import { Tag } from '@/components/ui/tag';
import type {
  PurchaseOrder,
  PurchaseOrderStatus,
  UpdatePurchaseOrderInput,
} from '@/pages/purchase-orders/api/purchase-orders-api';

const STATUS_LABEL: Record<PurchaseOrderStatus, string> = {
  DRAFT: '초안',
  CONFIRMED: '확정',
  RECEIVED: '입고 완료',
  CANCELLED: '취소',
};

const STATUS_VARIANT: Record<PurchaseOrderStatus, 'warning' | 'info' | 'success' | 'default'> = {
  DRAFT: 'warning',
  CONFIRMED: 'info',
  RECEIVED: 'success',
  CANCELLED: 'default',
};

interface PurchaseOrderCardProps {
  order: PurchaseOrder;
  suppliers: { id: string; name: string }[];
  warehouses: { id: string; name: string }[];
  canManage: boolean;
  busy: boolean;
  onUpdate: (input: UpdatePurchaseOrderInput) => void;
  onConfirm: () => void;
  onCancel: () => void;
  onReceive: (warehouseId: string) => void;
}

function PurchaseOrderCard({
  order,
  suppliers,
  warehouses,
  canManage,
  busy,
  onUpdate,
  onConfirm,
  onCancel,
  onReceive,
}: PurchaseOrderCardProps) {
  const [quantities, setQuantities] = useState<Record<string, string>>({});
  const [warehouseId, setWarehouseId] = useState('');
  const isDraft = order.status === 'DRAFT';
  const total = order.items.reduce((sum, item) => sum + Number(item.unitCost) * item.quantity, 0);

  const changed = order.items.filter((item) => {
    const edited = quantities[item.id];
    return edited !== undefined && Number(edited) !== item.quantity && Number(edited) >= 1;
  });

  function saveQuantities() {
    onUpdate({ items: changed.map((item) => ({ itemId: item.id, quantity: Number(quantities[item.id]) })) });
    setQuantities({});
  }

  return (
    <Card className="flex flex-col gap-4 p-5">
      <div className="flex flex-wrap items-center justify-between gap-2">
        <div className="flex items-center gap-2">
          <span className="font-semibold">{order.orderNo}</span>
          <Badge variant={STATUS_VARIANT[order.status]}>{STATUS_LABEL[order.status]}</Badge>
          {order.isAutoGenerated && <Tag>자동 생성</Tag>}
        </div>
        <span className="text-sm text-muted-foreground">합계 {total.toLocaleString()}원</span>
      </div>

      <div className="flex flex-wrap items-center gap-2 text-sm">
        <span className="text-muted-foreground">공급처</span>
        {isDraft && canManage ? (
          <Select value={order.partnerId ?? ''} onValueChange={(partnerId) => onUpdate({ partnerId })}>
            <SelectTrigger className="w-56">
              <SelectValue placeholder="공급처를 선택하세요" />
            </SelectTrigger>
            <SelectContent>
              {suppliers.map((s) => (
                <SelectItem key={s.id} value={s.id}>
                  {s.name}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
        ) : (
          <span>{order.partner?.name ?? '-'}</span>
        )}
      </div>
      {isDraft && order.memo && <p className="text-sm text-warning-foreground">{order.memo}</p>}

      <ul className="flex flex-col divide-y divide-border rounded-md border border-border">
        {order.items.map((item) => (
          <li key={item.id} className="flex flex-wrap items-center justify-between gap-2 px-3 py-2 text-sm">
            <div className="flex flex-col">
              <span>
                {item.product.name} <span className="text-muted-foreground">({item.product.sku})</span>
              </span>
              {item.reason && <span className="text-xs text-muted-foreground">{item.reason}</span>}
            </div>
            {isDraft && canManage ? (
              <Input
                type="number"
                min={1}
                className="w-24"
                value={quantities[item.id] ?? String(item.quantity)}
                onChange={(e) => setQuantities((prev) => ({ ...prev, [item.id]: e.target.value }))}
                aria-label={`${item.product.name} 수량`}
              />
            ) : (
              <span>
                {item.quantity.toLocaleString()} {item.product.unit}
              </span>
            )}
          </li>
        ))}
      </ul>

      {canManage && isDraft && (
        <div className="flex flex-wrap justify-end gap-2">
          {changed.length > 0 && (
            <Button variant="secondary" onClick={saveQuantities} disabled={busy}>
              수량 저장
            </Button>
          )}
          <Button variant="secondary" onClick={onCancel}>
            취소
          </Button>
          <Button onClick={onConfirm} disabled={!order.partnerId || changed.length > 0}>
            확정
          </Button>
        </div>
      )}

      {canManage && order.status === 'CONFIRMED' && (
        <div className="flex flex-wrap items-center justify-end gap-2">
          <Select value={warehouseId} onValueChange={setWarehouseId}>
            <SelectTrigger className="w-44">
              <SelectValue placeholder="입고 창고" />
            </SelectTrigger>
            <SelectContent>
              {warehouses.map((w) => (
                <SelectItem key={w.id} value={w.id}>
                  {w.name}
                </SelectItem>
              ))}
            </SelectContent>
          </Select>
          <Button variant="secondary" onClick={onCancel}>
            취소
          </Button>
          <Button onClick={() => onReceive(warehouseId)} disabled={!warehouseId || busy}>
            입고 처리
          </Button>
        </div>
      )}
    </Card>
  );
}

export { PurchaseOrderCard };
